]

/// Draws `text` in the pixel font, each font pixel `scale` art pixels square, one blank column between letters.
/// Characters the font lacks are skipped.
func pixelText(_ text: String, color: CGColor, scale: Int = 2) -> CGImage? {
    let letters = text.uppercased().compactMap { glyphs[$0] }
    guard !letters.isEmpty else { return nil }
    let width = (letters.reduce(0) { $0 + $1[0].count } + letters.count - 1) * scale
    let height = 5 * scale
    guard let ctx = CGContext(data: nil, width: width, height: height, bitsPerComponent: 8, bytesPerRow: 0,
                              space: CGColorSpace(name: CGColorSpace.sRGB)!, bitmapInfo: CGImageAlphaInfo.premultipliedLast.rawValue)
    else { return nil }
    ctx.setFillColor(color)
    var x = 0
    for rows in letters {
        for (row, line) in rows.enumerated() {
            for (column, pixel) in line.enumerated() where pixel == "#" {
                ctx.fill(CGRect(x: (x + column) * scale, y: (4 - row) * scale, width: scale, height: scale))  // CG's origin is bottom-left
            }
        }
        x += rows[0].count + 1
    }
    return ctx.makeImage()
}
